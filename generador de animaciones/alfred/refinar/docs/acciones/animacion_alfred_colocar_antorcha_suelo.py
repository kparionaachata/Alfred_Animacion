def execute_animation(player_parts, start_frame=None, end_frame=None):
    """
    Slot 1: 'Colocar antorcha' de Alfred -- camina hasta el
    punto, se agacha, planta la antorcha en el suelo y se levanta.
    """
    start_frame = START_FRAME
    end_frame = END_FRAME

    armature = bpy.data.objects.get("Armature")
    if not armature or armature.type != 'ARMATURE':
        print("Error: No se encontro el Armature")
        return False

    if armature.mode != 'POSE':
        bpy.context.view_layer.objects.active = armature
        bpy.ops.object.mode_set(mode='POSE')

    alfred_root = next((o for o in bpy.data.objects if o.name == 'alfred' and o.type == 'EMPTY'), None)

    _arm_action_name  = f'slot_001_alfred_colocar_antorcha_arm'
    _root_action_name = f'slot_001_alfred_colocar_antorcha_root'

    if not armature.animation_data:
        armature.animation_data_create()
    _arm_existing = bpy.data.actions.get(_arm_action_name)
    if _arm_existing:
        bpy.data.actions.remove(_arm_existing)
    _arm_action = bpy.data.actions.new(name=_arm_action_name)
    armature.animation_data.action = _arm_action

    _bones_ok = 0
    for _bone_name, _frames in globals()['KEYFRAME_DATA'].items():
        _bone = armature.pose.bones.get(_bone_name)
        if not _bone:
            continue
        _bone.rotation_mode = 'XYZ'
        for _frame, _rot in _frames.items():
            _bone.rotation_euler = _rot
            _bone.keyframe_insert(data_path="rotation_euler", frame=_frame)
        _bones_ok += 1

    for _fc in _get_fcurves(_arm_action):
        for _kp in _fc.keyframe_points:
            _kp.interpolation = 'BEZIER'
            _kp.easing = 'AUTO'

    if alfred_root is not None:
        if not alfred_root.animation_data:
            alfred_root.animation_data_create()
        _root_existing = bpy.data.actions.get(_root_action_name)
        if _root_existing:
            bpy.data.actions.remove(_root_existing)
        _root_action = bpy.data.actions.new(name=_root_action_name)
        alfred_root.animation_data.action = _root_action

        for _frame in sorted(ROOT_LOCATION_DATA.keys()):
            alfred_root.location = ROOT_LOCATION_DATA[_frame]
            alfred_root.keyframe_insert(data_path="location", frame=_frame)
        for _frame in sorted(ROOT_ROTATION_DATA.keys()):
            alfred_root.rotation_euler = ROOT_ROTATION_DATA[_frame]
            alfred_root.keyframe_insert(data_path="rotation_euler", frame=_frame)

        for _fc in _get_fcurves(_root_action):
            for _kp in _fc.keyframe_points:
                _kp.interpolation = 'BEZIER'
                _kp.easing = 'AUTO'

    print(f"[Slot 1] colocar_antorcha aplicado ({_bones_ok} bones, "
          f"{start_frame}-{end_frame}), antorcha destino: {TORCH_TARGET_COORDS}")

    # ============================================
    # EMPUJAR ACCIONES AL NLA
    # ============================================
    # FIX (Kebyn, 2026-08-21): sin este bloque (presente en generate_saltar_subir/
    # generate_saltar_bajar/generate_caminar pero faltante aca) la accion de este
    # slot quedaba como armature.animation_data.action "suelta" -- el SIGUIENTE
    # slot del recorrido la pisaba al asignar la suya propia, y el bake final
    # (bpy.ops.nla.bake sobre los NLA tracks) no encontraba NINGUN strip cubriendo
    # este rango de frames, dejando a Alfred en pose T durante todo el tramo
    # colocar_antorcha (tanto en Reproducir recorrido como en la exportacion).
    if armature.animation_data and armature.animation_data.action:
        _arm_done  = armature.animation_data.action
        armature.animation_data.action = None
        _arm_track = armature.animation_data.nla_tracks.new()
        _arm_track.name = f'Slot_001_arm'
        _arm_strip = _arm_track.strips.new(_arm_done.name, start_frame, _arm_done)
        _arm_strip.frame_end      = end_frame
        _arm_strip.extrapolation  = 'NOTHING'
        _arm_strip.use_auto_blend = False
        _arm_strip.blend_in       = 0
        _arm_strip.blend_out      = 0

    if alfred_root and alfred_root.animation_data and alfred_root.animation_data.action:
        _root_done  = alfred_root.animation_data.action
        alfred_root.animation_data.action = None
        _root_track = alfred_root.animation_data.nla_tracks.new()
        _root_track.name = f'Slot_001_root'
        _root_strip = _root_track.strips.new(_root_done.name, start_frame, _root_done)
        _root_strip.frame_end      = end_frame
        _root_strip.extrapolation  = 'HOLD_FORWARD'
        _root_strip.use_auto_blend = False
        _root_strip.blend_in       = 0
        _root_strip.blend_out      = 0

    return True


if __name__ == "__main__":
    execute_animation(None, start_frame=START_FRAME, end_frame=END_FRAME)
