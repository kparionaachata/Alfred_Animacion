    prev_rot  = _base_rz
    trans_start = None
    trans_start_rot = None

    for frame in range(1, 31):
        angle_diff = _angle_diff_shortest(target_rz, prev_rot)
        if abs(angle_diff) < 0.1:
            smoothed = target_rz
            trans_start = None
        else:
            if trans_start is None:
                trans_start = frame
                trans_start_rot = prev_rot
            elapsed  = frame - trans_start
            progress = min(elapsed / smoothing, 1.0)
            eased    = _smoothstep_val(progress)
            smoothed = trans_start_rot + _angle_diff_shortest(target_rz, trans_start_rot) * eased
            if progress >= 1.0:
                prev_rot   = target_rz
                trans_start = None

        data[frame] = (_math.radians(0), _math.radians(0), _math.radians(smoothed))
    return data

