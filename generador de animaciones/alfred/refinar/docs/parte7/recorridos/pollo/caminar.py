def _compute_direction_angle(p0, p1):
    dx = p1['x'] - p0['x']
    dy = p1['y'] - p0['y']
    if dx == 0 and dy == 0:
        return None
    ang_raw = math.degrees(math.atan2(dx, dy))
    ang_rounded = round(ang_raw / 90.0) * 90.0
    ang_diff = abs(ang_raw - ang_rounded)
    ang = ang_rounded if ang_diff < 45 else -ang_raw
    while ang >  180: ang -= 360
    while ang < -180: ang += 360
    if   ang ==  90: ang = -90
    elif ang == -90: ang =  90
    return ang

def _smoothstep_val(x):
    if x <= 0: return 0.0
    if x >= 1: return 1.0
    return x * x * (3.0 - 2.0 * x)

def _angle_diff_shortest(target, current):
    d = target - current
    while d >  180: d -= 360
    while d < -180: d += 360
    return d

def _build_rotation_data():
    """Orientación suavizada tramo a tramo, usando _SEGMENT_DIRECTIONS."""
    data = {}
    smoothing = 8
    prev_rot = _base_rz
    trans_start = None
    trans_start_rot = None

    for (f0, f1, ang) in _SEGMENT_DIRECTIONS:
        target_rz = ang if ang is not None else _base_rz
        for frame in range(f0, f1 + 1):
            angle_diff = _angle_diff_shortest(target_rz, prev_rot)
            if abs(angle_diff) < 0.1:
                smoothed = target_rz
                trans_start = None
            else:
                if trans_start is None:
                    trans_start = frame
                    trans_start_rot = prev_rot
                elapsed  = frame - trans_start
                progress = min(elapsed / smoothing, 1.0)
                eased    = _smoothstep_val(progress)
                smoothed = trans_start_rot + _angle_diff_shortest(target_rz, trans_start_rot) * eased
                if progress >= 1.0:
                    prev_rot = target_rz
                    trans_start = None
            data[frame] = (math.radians(0), math.radians(0), math.radians(smoothed))
        prev_rot = target_rz

    return data

