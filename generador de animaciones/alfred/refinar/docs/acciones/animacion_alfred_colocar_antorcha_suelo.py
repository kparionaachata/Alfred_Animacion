def _compute_direction_angle(p0, p1):
    """Angulo de orientacion cardinal/diagonal para el segmento p0->p1."""
    dx = p1['x'] - p0['x']
    dy = p1['y'] - p0['y']
    if dx == 0 and dy == 0:
        return None
    ang_raw = math.degrees(math.atan2(dx, dy))
    ang_rounded = round(ang_raw / 90.0) * 90.0
    ang_diff = abs(ang_raw - ang_rounded)
    ang = ang_rounded if ang_diff < 45 else -ang_raw
    while ang >  180: ang -= 360
    while ang < -180: ang += 360
    if   ang ==  90: ang = -90
    elif ang == -90: ang =  90
    return ang

def _smoothstep_val(x):
    if x <= 0: return 0.0
    if x >= 1: return 1.0
    return x * x * (3.0 - 2.0 * x)

def _angle_diff_shortest(target, current):
    d = target - current
    while d >  180: d -= 360
    while d < -180: d += 360
    return d

